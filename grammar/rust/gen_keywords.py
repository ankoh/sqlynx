#!/usr/bin/env python3
"""Generate the Rust keyword table of the scanner from grammar/lists/*.list.

Each list line is an X-macro `X(CATEGORY, "name", TOKEN)`, shared with the C++ scanner. The
output is a Rust module (to be declared inside dashql-grammar, next to `tables`) that defines
`KEYWORDS`, sorted by name for binary search, and `MAX_KEYWORD_LENGTH`.
"""

import argparse
import re
import sys

ENTRY = re.compile(r'^X\((\w+),\s*"([^"]+)",\s*(\w+)\)\s*$')

CATEGORIES = {
    "SQL_COLUMN_NAME": "SqlColumnName",
    "SQL_RESERVED": "SqlReserved",
    "SQL_TYPE_FUNC": "SqlTypeFunc",
    "SQL_UNRESERVED": "SqlUnreserved",
    "VIS_UNRESERVED": "VisUnreserved",
}


def read_lists(paths):
    keywords = []
    for path in paths:
        with open(path, encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#") or line.startswith("//"):
                    continue
                m = ENTRY.match(line)
                if not m:
                    raise SystemExit(f"{path}: cannot parse {line!r}")
                category, name, token = m.groups()
                if category not in CATEGORIES:
                    raise SystemExit(f"{path}: unknown category {category}")
                keywords.append((name, token, CATEGORIES[category]))
    names = [k[0] for k in keywords]
    duplicates = sorted({n for n in names if names.count(n) > 1})
    if duplicates:
        raise SystemExit(f"duplicate keywords: {duplicates}")
    return sorted(keywords, key=lambda k: k[0].encode("utf-8"))


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True)
    parser.add_argument("lists", nargs="+")
    args = parser.parse_args()

    keywords = read_lists(args.lists)
    out = [
        "// Generated by //grammar/rust:gen_keywords.py from grammar/lists/*.list. DO NOT EDIT.",
        "",
        "use super::{symbol_kind, Keyword, KeywordCategory};",
        "",
        f"/// The length of the longest keyword.",
        f"pub const MAX_KEYWORD_LENGTH: usize = {max(len(k[0]) for k in keywords)};",
        "",
        "/// All keywords, sorted by name.",
        "pub static KEYWORDS: &[Keyword] = &[",
    ]
    for name, token, category in keywords:
        out.append(
            f'    Keyword {{ name: "{name}", symbol: symbol_kind::S_{token}, category: KeywordCategory::{category} }},'
        )
    out.append("];")
    with open(args.output, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
