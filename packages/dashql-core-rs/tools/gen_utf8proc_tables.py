#!/usr/bin/env python3
"""Emit the utf8proc properties that the shell reads (charwidth, boundclass) as Rust.

Reads the vendored `packages/dashql-core/vendor/utf8proc/utf8proc.data` (utf8proc 2.4.0, Unicode
12.1.0) and its header, resolves the two-stage property lookup of `unsafe_get_property` for every
code point, and run-length encodes the result:

    pub(super) static RUNS: [(u32, u8); N]

Each run starts at a code point and holds `charwidth | boundclass << 2` for all code points up to
the next run.
"""

import argparse
import re


def parse_array(data: str, name: str) -> str:
    match = re.search(r"\b" + re.escape(name) + r"\[\]\s*=\s*\{(.*?)\n\};", data, re.S)
    if match is None:
        raise SystemExit(f"array {name} not found")
    return match.group(1)


def parse_ints(body: str) -> list[int]:
    return [int(v) for v in re.findall(r"-?\d+", body)]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", required=True)
    parser.add_argument("--header", required=True)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()

    with open(args.header, encoding="utf-8") as f:
        header = f.read()
    boundclasses = {name: int(value) for name, value in re.findall(r"(UTF8PROC_BOUNDCLASS_\w+)\s*=\s*(\d+)", header)}

    with open(args.data, encoding="utf-8") as f:
        data = f.read()
    stage1 = parse_ints(parse_array(data, "utf8proc_stage1table"))
    stage2 = parse_ints(parse_array(data, "utf8proc_stage2table"))
    properties = []
    for entry in re.findall(r"\{([^{}]*)\}", parse_array(data, "utf8proc_properties")):
        fields = [field.strip() for field in entry.split(",")]
        if len(fields) != 17:
            raise SystemExit(f"unexpected property entry: {entry}")
        charwidth = int(fields[14])
        boundclass = boundclasses[fields[16]]
        if not 0 <= charwidth <= 3:
            raise SystemExit(f"unexpected charwidth: {entry}")
        properties.append(charwidth | (boundclass << 2))

    runs = []
    for cp in range(0x110000):
        value = properties[stage2[stage1[cp >> 8] + (cp & 0xFF)]]
        if not runs or runs[-1][1] != value:
            runs.append((cp, value))

    with open(args.output, "w", encoding="utf-8") as out:
        out.write("// Generated by packages/dashql-core-rs/tools/gen_utf8proc_tables.py, do not edit.\n\n")
        out.write("/// The utf8proc properties as runs of (first code point, charwidth | boundclass << 2)\n")
        out.write(f"pub(super) static RUNS: [(u32, u8); {len(runs)}] = [\n")
        for cp, value in runs:
            out.write(f"    (0x{cp:X}, {value}),\n")
        out.write("];\n")
        out.write(f"\n/// The properties of code points outside the code space (`utf8proc_properties[0]`)\n")
        out.write(f"pub(super) const INVALID: u8 = {properties[0]};\n")


if __name__ == "__main__":
    main()
