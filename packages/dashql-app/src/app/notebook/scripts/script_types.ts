/// A script in the collection (runtime representation)
export interface Script {
    // The script id
    scriptId: number;
    // The script text
    scriptText: string;
    // The script annotations
    annotations: ScriptAnnotations;
}

/// A reference in the notebook's flat ordered script collection.
export interface ScriptRef {
    // The script id
    scriptId: number;
    // The explicit file name (e.g., "01-script.sql")
    fileName: string;
}

