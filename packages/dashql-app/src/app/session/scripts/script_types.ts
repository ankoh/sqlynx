import type * as app_session from '@ankoh/dashql-jsonschema/app_session.js';
import type { TopLevelSpec } from 'vega-lite';

import type * as core_buffers from '@ankoh/dashql-core/buffers';
import type { UmapRequest } from '../../../compute/umap/umap_projection.js';
import { umapRequestFromSpec } from '../compute/ui/visualization/umap/umap_spec.js';
import { randomScriptName } from './script_name.js';

export interface DashboardSpec {
    row?: number | null;
    column?: number | null;
    width?: number | null;
    height?: number | null;
}

/// Script collection type definitions.
///
/// These types represent the runtime state of the session's scripts.
/// Storage format types (SessionMetadata, SessionOriginType) come from JSON Schema.

// Re-export storage format types from JSON Schema
export type SessionMetadata = app_session.SessionMetadata;
export type SessionOriginType = NonNullable<app_session.SessionMetadata['originType']>;

/// A visualize statement resolved against the session. Discriminated on the
/// renderer named after `USING`: `vegalite` carries a parsed Vega-Lite spec,
/// `umap` carries the projection spec for the WebGPU scatter renderer.
/// Both carry the SQL to execute against the backend.
export type ResolvedVisualizeQuery =
    | {
          renderer: 'vegalite';
          // The SQL to execute against the backend
          sql: string;
          // The Vega-Lite spec generated by the analyzer
          vegaLiteSpec: TopLevelSpec;
          dashboardSpec?: DashboardSpec | null;
      }
    | {
          renderer: 'umap';
          // The SQL to execute against the backend
          sql: string;
          // The UMAP projection spec compiled by dashql-core.
          umapSpec: core_buffers.visualization.UmapSpecT;
          dashboardSpec?: DashboardSpec | null;
      }
    | {
          renderer: 'markdown';
          // The SQL to execute against the backend
          sql: string;
          // The row template compiled by dashql-core.
          markdownSpec: core_buffers.visualization.MarkdownSpecT;
          dashboardSpec?: DashboardSpec | null;
      }
    | {
          renderer: 'table';
          // The SQL to execute against the backend
          sql: string;
          dashboardSpec?: DashboardSpec | null;
      };

/// Derive the compute-layer UMAP projection request from a resolved visualize query.
/// Returns undefined for non-`umap` renderers (or none), so it can be spread directly
/// into `QueryExecutionArgs.projection` at the execute sites.
export function projectionForVisualizeQuery(query: ResolvedVisualizeQuery | null | undefined): UmapRequest | undefined {
    return query?.renderer === 'umap' ? umapRequestFromSpec(query.umapSpec) : undefined;
}

/// Script annotations derived from analysis
export interface ScriptAnnotations {
    // The table definitions
    tableDefs: string[];
    // The resolved VISUALIZE query for this script, if any.
    visualizeQuery: ResolvedVisualizeQuery | null;
}

/// A reference in the session's flat ordered script collection.
export interface ScriptRef {
    // The script id
    scriptId: number;
    // The file name (e.g., "extract.sql")
    fileName: string;
}

/// Helper to create empty annotations
export function createEmptyAnnotations(): ScriptAnnotations {
    return {
        tableDefs: [],
        visualizeQuery: null,
    };
}

/// Helper to create empty metadata
export function createEmptyMetadata(): SessionMetadata {
    return {
        originType: 'LOCAL',
        originalFileName: '',
        originalHttpUrl: '',
    };
}

/// Trailing ".sql" extension, stripped for display.
const SCRIPT_EXTENSION_RE = /\.sql$/i;

/// The display name of a script, its file name without the ".sql" extension.
/// "01_extract.sql" -> "01_extract". Used for tab/feed/details labels and to pre-fill the rename input.
export function scriptDisplayName(fileName: string): string {
    return fileName.replace(SCRIPT_EXTENSION_RE, '');
}

/// Return a script base name (no extension) that is unique among the display names of the existing
/// scripts, suffixing "-2", "-3", ... on collision.
export function uniqueScriptBase(
    base: string,
    existingScripts: { [fileName: string]: ScriptRef },
    excludeFileName: string = '',
): string {
    const taken = new Set<string>();
    for (const key of Object.keys(existingScripts)) {
        if (key === excludeFileName) continue;
        taken.add(scriptDisplayName(key).toLowerCase());
    }
    let candidate = base;
    for (let suffix = 2; taken.has(candidate.toLowerCase()); ++suffix) {
        candidate = `${base}-${suffix}`;
    }
    return candidate;
}

/// Helper to generate a script file name that doesn't collide with existing entries, a random
/// "<adjective>_<animal>" name by default or the explicit `base` if given, e.g. "brave_otter.sql".
/// The order of the scripts lives in the session file, not in the file names.
export function generateScriptFileName(
    existingScripts: { [fileName: string]: ScriptRef },
    base?: string,
): string {
    const requested = base ?? randomScriptName(new Set(Object.keys(existingScripts).map(scriptDisplayName)));
    return `${uniqueScriptBase(requested, existingScripts)}.sql`;
}

/// Helper to create a committed script entry.
export function createScriptRef(scriptId: number, fileName: string): ScriptRef {
    return {
        scriptId,
        fileName,
    };
}
