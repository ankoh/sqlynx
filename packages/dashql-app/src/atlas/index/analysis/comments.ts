import { buffers } from '@ankoh/dashql-core';
import type { AnalyzedSql } from './core.js';

export const DESCRIPTION_BEGIN = '@dashql:description';
export const DESCRIPTION_END = '@dashql:end';

export type CommentSource = 'dashql_description' | 'dashql_metadata' | 'comment';

export interface CommentBlock {
    source: CommentSource;
    /// The comment text without comment markers
    text: string;
    /// UTF-8 byte range in the script. For descriptions this covers the marker lines.
    begin: number;
    end: number;
}

const decoder = new TextDecoder();

/// Extract the comment blocks of an analyzed script in script order.
/// DashQL core groups the comments, descriptions generated by `describe` are blocks of their own.
/// Blocks with unknown `@dashql:` tags are machine annotations and are skipped.
export function extractComments(sql: AnalyzedSql): CommentBlock[] {
    const parsed = sql.parsed;
    if (!parsed) {
        return [];
    }
    const blocks: CommentBlock[] = [];
    const block = new buffers.parser.CommentBlock();
    const line = new buffers.parser.TextSpan();
    for (let i = 0; i < parsed.commentBlocksLength(); ++i) {
        parsed.commentBlocks(i, block);
        let source: CommentSource;
        switch (block.blockType()) {
            case buffers.parser.CommentBlockType.COMMENT:
                source = 'comment';
                break;
            case buffers.parser.CommentBlockType.DASHQL_DESCRIPTION:
                source = 'dashql_description';
                break;
            case buffers.parser.CommentBlockType.DASHQL_METADATA:
                source = 'dashql_metadata';
                break;
            default:
                continue;
        }
        const lines: string[] = [];
        for (let j = 0; j < block.linesCount(); ++j) {
            parsed.commentLines(block.linesBegin() + j, line);
            lines.push(decoder.decode(sql.bytes.subarray(line.offset(), line.offset() + line.length())));
        }
        const text = lines.join('\n');
        // Tagged blocks are kept even when empty so that `describe` can replace or skip them
        if (text.length === 0 && source === 'comment') {
            continue;
        }
        const span = block.textSpan()!;
        blocks.push({ source, text, begin: span.offset(), end: span.offset() + span.length() });
    }

    return blocks;
}

/// The text of the `@dashql:description` blocks that is embedded, null if there is none.
/// Ordinary comments are not embedded, they are too often commented-out SQL or notes that say little about a script.
export function descriptionText(blocks: CommentBlock[]): string | null {
    const description = blocks.filter(b => b.source === 'dashql_description').map(b => b.text).join('\n\n');
    return description.length > 0 ? description : null;
}
