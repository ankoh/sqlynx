import type { AnalyzedSql, SqlAnalyzer } from './core.js';

export const DESCRIPTION_BEGIN = '@dashql:description';
export const DESCRIPTION_END = '@dashql:end';

export type CommentSource = 'dashql_description' | 'comment';

export interface CommentBlock {
    source: CommentSource;
    /// The comment text without comment markers
    text: string;
    /// UTF-8 byte range in the script. For descriptions this covers the marker lines.
    begin: number;
    end: number;
    /// True if the text parses as SQL (commented-out code)
    isCode: boolean;
}

const decoder = new TextDecoder();

interface CommentLine {
    text: string;
    begin: number;
    end: number;
}

function stripLineComment(raw: string): string {
    return raw.replace(/^--+ ?/, '').trimEnd();
}

function stripBlockComment(raw: string): string[] {
    const inner = raw.replace(/^\/\*+/, '').replace(/\*+\/$/, '');
    return inner
        .split('\n')
        .map(line => line.replace(/^\s*\* ?/, '').trim())
        .filter((line, i, all) => !((i === 0 || i === all.length - 1) && line === ''));
}

const CODE_START = /^\s*(select|with|insert|update|delete|create|drop|alter|explain|set|attach|copy|values)\b/i;

/// Extract the comment blocks of an analyzed script in script order.
/// Contiguous line comments are merged, descriptions generated by `describe` are split off.
export function extractComments(sql: AnalyzedSql, analyzer?: SqlAnalyzer): CommentBlock[] {
    const parsed = sql.parsed;
    if (!parsed) {
        return [];
    }
    const blocks: CommentBlock[] = [];
    let run: CommentLine[] = [];
    let runEnd = -1;

    const flushHuman = (lines: CommentLine[]) => {
        if (lines.length === 0) return;
        const text = lines.map(l => l.text).join('\n').trim();
        if (text.length > 0) {
            blocks.push({ source: 'comment', text, begin: lines[0].begin, end: lines[lines.length - 1].end, isCode: false });
        }
    };
    const flushRun = () => {
        let human: CommentLine[] = [];
        let description: CommentLine[] | null = null;
        for (const line of run) {
            const marker = line.text.trim();
            if (description === null && marker === DESCRIPTION_BEGIN) {
                flushHuman(human);
                human = [];
                description = [line];
            } else if (description !== null && marker === DESCRIPTION_END) {
                description.push(line);
                const body = description.slice(1, -1).map(l => l.text).join('\n').trim();
                blocks.push({
                    source: 'dashql_description',
                    text: body,
                    begin: description[0].begin,
                    end: line.end,
                    isCode: false,
                });
                description = null;
            } else if (description !== null) {
                description.push(line);
            } else {
                human.push(line);
            }
        }
        // An unterminated description is treated as an ordinary comment
        flushHuman(description !== null ? [...human, ...description.slice(1)] : human);
        run = [];
    };

    for (let i = 0; i < parsed.commentsLength(); ++i) {
        const span = parsed.comments(i)!;
        const begin = span.offset();
        const end = begin + span.length();
        const raw = decoder.decode(sql.bytes.subarray(begin, end));
        if (raw.startsWith('--')) {
            // Contiguous means only whitespace with a single line break in between
            const gap = runEnd >= 0 ? decoder.decode(sql.bytes.subarray(runEnd, begin)) : null;
            if (gap === null || (/^\s*$/.test(gap) && (gap.match(/\n/g)?.length ?? 0) <= 1)) {
                run.push({ text: stripLineComment(raw), begin, end });
            } else {
                flushRun();
                run.push({ text: stripLineComment(raw), begin, end });
            }
            runEnd = end;
        } else {
            flushRun();
            runEnd = -1;
            const lines = stripBlockComment(raw);
            const text = lines.join('\n').trim();
            if (text.length > 0) {
                blocks.push({ source: 'comment', text, begin, end, isCode: false });
            }
        }
    }
    flushRun();

    // Detect commented-out SQL
    if (analyzer) {
        const candidates = blocks.filter(b => b.source === 'comment' && CODE_START.test(b.text));
        const verdicts = analyzer.parsesAsSql(candidates.map(b => b.text));
        candidates.forEach((block, i) => {
            block.isCode = verdicts[i];
        });
    }
    return blocks;
}

/// The comment text that should be embedded, description first and without commented-out code
export function embeddableComments(blocks: CommentBlock[]): { source: CommentSource; text: string }[] {
    const out: { source: CommentSource; text: string }[] = [];
    const description = blocks.filter(b => b.source === 'dashql_description').map(b => b.text).join('\n\n');
    if (description.length > 0) {
        out.push({ source: 'dashql_description', text: description });
    }
    const comments = blocks.filter(b => b.source === 'comment' && !b.isCode).map(b => b.text).join('\n\n');
    if (comments.length > 0) {
        out.push({ source: 'comment', text: comments });
    }
    return out;
}
